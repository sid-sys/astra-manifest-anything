import 'package:astra/admin/admin_models.dart';

/// A person written out by hand for the admin tests.
AdminUser makeUser({
  String id = 'abcdef123456',
  String name = '',
  String email = '',
  bool isGuest = false,
  DateTime? joinedAt,
  AdminPlan plan = AdminPlan.none,
  bool ever = false,
  bool testPurchase = false,
  int? onboardingSeconds,
  bool onboarded = true,
  bool typed = false,
  int paywall = 0,
  int attempts = 0,
  String heardFrom = '',
  Set<String> openDays = const {},
  Map<String, DateTime> steps = const {},
  List<AdminPayment> payments = const [],
  List<PayFailure> failures = const [],
  List<AdminEvent> events = const [],
  DateTime? installedAt,
  DateTime? uninstalledAt,
}) {
  final joined = joinedAt ?? DateTime.now().subtract(const Duration(days: 10));
  return AdminUser(
    id: id,
    name: name,
    email: email,
    country: 'Kolkata',
    joinedAt: joined,
    lastSeen: events.isEmpty ? joined : events.first.time,
    isGuest: isGuest,
    plan: plan,
    everSubscribed: ever || plan != AdminPlan.none,
    subscribedAt: ever ? joined : null,
    expiryTime: null,
    testPurchase: testPurchase,
    onboardingSeconds: onboardingSeconds,
    onboardingComplete: onboarded,
    heardFrom: heardFrom,
    answers: const {'belief': 'absolutely', 'areas': ['peace']},
    steps: steps,
    openDays: openDays,
    events: events,
    payFailures: failures,
    paywallViews: paywall,
    paymentAttempts: attempts,
    typedWish: typed,
    payments: payments,
    manifestations: const [],
    affirmationSets: const [],
    installedAt: installedAt,
    uninstalledAt: uninstalledAt,
  );
}
